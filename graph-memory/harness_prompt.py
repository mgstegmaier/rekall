"""One filter for prompts the harness wrote, shared by the recall hook and the session digest."""

import re

# Harness written user events. None of these are you typing.
INJECTED = (
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "<command-message>",
    "<command-name>",
    "<command-args>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<user-prompt-submit-hook>",
    "<session-start-hook>",
    "<post-tool-use-hook>",
    "<task-notification",
    "<cross-session-message",
    "<teammate-message",
    "Another Claude session sent a message:",
    "[Cross-session idle notice]",
    "[Request interrupted",
    "Caveat: The messages below were generated by the user",
    "Tool loaded.",
    "This session is being continued",
    "Base directory for this skill",
)

REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)


def is_harness(prompt):
    """True when the prompt is empty or harness-written once reminder blocks are stripped.
    A reminder block followed by a typed question is a real prompt."""
    body = REMINDER.sub("", prompt).strip()
    return not body or body.startswith(INJECTED)
